// Generates src/_tokens.scss from the Flexoki palette's CSS custom properties.
//
// Usage: node scripts/sync-tokens.ts [path/to/flexoki.css]
// Without a path, the pinned upstream file is downloaded.
import { readFile, writeFile } from "node:fs/promises";
import { HUES, SHADES } from "./palette.ts";

const COMMIT = "8d723bac4a9ac46adfdf99d42155286977aac72a";
const SOURCE = `https://github.com/kepano/flexoki/blob/${COMMIT}/css/flexoki.css`;
const RAW_SOURCE = `https://raw.githubusercontent.com/kepano/flexoki/${COMMIT}/css/flexoki.css`;
const OUTPUT = new URL("../src/_tokens.scss", import.meta.url);

async function load(path: string | undefined): Promise<string> {
  if (path) {
    return readFile(path, "utf8");
  }
  const response = await fetch(RAW_SOURCE);
  if (!response.ok) {
    throw new Error(`Failed to download ${RAW_SOURCE}: ${response.status}`);
  }
  return response.text();
}

function parse(css: string): Map<string, string> {
  const tokens = new Map<string, string>();
  for (const [, name, value] of css.matchAll(/--flexoki-([a-z0-9-]+):\s*(#[0-9a-f]{6});/gi)) {
    // Upstream names base shades without a hue (--flexoki-150); call them base-150.
    tokens.set(/^\d+$/.test(name) ? `base-${name}` : name, value.toLowerCase());
  }
  return tokens;
}

function validate(tokens: Map<string, string>): void {
  const expected = [
    "paper",
    "black",
    ...["base", ...HUES].flatMap((hue) => SHADES.map((shade) => `${hue}-${shade}`)),
  ];
  const missing = expected.filter((name) => !tokens.has(name));
  const unexpected = [...tokens.keys()].filter((name) => !expected.includes(name));
  if (missing.length > 0 || unexpected.length > 0) {
    throw new Error(
      `Unexpected Flexoki palette. Missing: ${missing.join(", ") || "none"}. ` +
        `Unexpected: ${unexpected.join(", ") || "none"}.`,
    );
  }
}

// A Sass map entry for each of a hue's shades.
function map(hue: string, indent: string): string[] {
  return SHADES.map((shade) => `${indent}${shade}: $${hue}-${shade},`);
}

function render(tokens: Map<string, string>): string {
  const variables = (hue: string): string[] =>
    SHADES.map((shade) => `$${hue}-${shade}: ${tokens.get(`${hue}-${shade}`)};`);

  return [
    "// Generated by scripts/sync-tokens.ts. Do not edit by hand.",
    `// Source: ${SOURCE}`,
    "// Flexoki is copyright (c) 2023 Steph Ango and released under the MIT License.",
    "",
    `$paper: ${tokens.get("paper")};`,
    `$black: ${tokens.get("black")};`,
    "",
    ...["base", ...HUES].flatMap((hue) => [`// ${hue}`, ...variables(hue), ""]),
    "// Maps for loops",
    "$base: (",
    ...map("base", "  "),
    ");",
    "$accents: (",
    ...HUES.flatMap((hue) => [`  "${hue}": (`, ...map(hue, "    "), "  ),"]),
    ");",
    "",
  ].join("\n");
}

const tokens = parse(await load(process.argv[2]));
validate(tokens);
await writeFile(OUTPUT, render(tokens));
console.log(`Wrote ${tokens.size} Flexoki tokens to src/_tokens.scss`);
